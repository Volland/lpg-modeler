import { build } from 'esbuild'
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
export const BUNDLE = join(ROOT, 'docs', 'playground', 'lpg-core.js')

/**
 * `core` resolves an import with `node:path`, and a page has no neighbouring files to
 * import from, so the only call that matters — `resolve(dirname(file), imported)` — is
 * all the shim carries. See lat.md/playground#Playground.
 */
const PATH_SHIM = `
export const dirname = (p) => p.slice(0, Math.max(p.lastIndexOf('/'), 0)) || '/'
export const resolve = (...parts) => {
  const out = []
  for (const seg of parts.join('/').split('/')) {
    if (seg === '..') out.pop()
    else if (seg && seg !== '.') out.push(seg)
  }
  return '/' + out.join('/')
}
`

/** The bundle as text; the test builds it again and compares, so it can never go stale. */
export async function buildPlayground() {
  const result = await build({
    entryPoints: [join(ROOT, 'packages', 'core', 'src', 'browser.ts')],
    bundle: true,
    write: false,
    format: 'iife',
    globalName: 'LpgCore',
    platform: 'browser',
    target: 'es2020',
    minify: true,
    legalComments: 'none',
    banner: { js: '/* Generated by scripts/build-playground.mjs from packages/core. Do not edit. */' },
    logLevel: 'warning',
    plugins: [{
      name: 'node-path-shim',
      setup(b) {
        b.onResolve({ filter: /^node:path$/ }, () => ({ path: 'path', namespace: 'shim' }))
        b.onLoad({ filter: /.*/, namespace: 'shim' }, () => ({ contents: PATH_SHIM, loader: 'js' }))
      },
    }],
  })
  return result.outputFiles[0].text
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = await buildPlayground()
  writeFileSync(BUNDLE, text)
  console.log(`${BUNDLE} (${Math.round(text.length / 1024)} KiB)`)
}
