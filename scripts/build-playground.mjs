import { build } from 'esbuild'
import { createHash } from 'node:crypto'
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
export const BUNDLE = join(ROOT, 'docs', 'playground', 'lpg-core.js')
export const PAGE = join(ROOT, 'docs', 'playground.html')

/**
 * The page asks for the bundle by a hash of its content. The site sits behind a CDN that
 * keeps a script for hours, so a rebuilt bundle at an unchanged URL is not seen, and a page
 * that expects the new bundle runs against the old one.
 */
export const stamp = (text) => createHash('sha256').update(text).digest('hex').slice(0, 10)

/** The page with its script tag pointing at the bundle `text` would be written as. */
export function stampedPage(page, text) {
  return page.replace(/<script src="playground\/lpg-core\.js(\?v=[0-9a-f]+)?"><\/script>/, `<script src="playground/lpg-core.js?v=${stamp(text)}"></script>`)
}

/**
 * `core` resolves an import with `node:path`, and a page has no neighbouring files to
 * import from, so the only call that matters — `resolve(dirname(file), imported)` — is
 * all the shim carries. See lat.md/playground#Playground.
 */
const PATH_SHIM = `
export const dirname = (p) => p.slice(0, Math.max(p.lastIndexOf('/'), 0)) || '/'
export const resolve = (...parts) => {
  const out = []
  for (const seg of parts.join('/').split('/')) {
    if (seg === '..') out.pop()
    else if (seg && seg !== '.') out.push(seg)
  }
  return '/' + out.join('/')
}
`

/** The bundle as text; the test builds it again and compares, so it can never go stale. */
export async function buildPlayground() {
  const result = await build({
    entryPoints: [join(ROOT, 'packages', 'core', 'src', 'browser.ts')],
    bundle: true,
    write: false,
    format: 'iife',
    globalName: 'LpgCore',
    platform: 'browser',
    target: 'es2020',
    minify: true,
    legalComments: 'none',
    banner: { js: '/* Generated by scripts/build-playground.mjs from packages/core. Do not edit. */' },
    logLevel: 'warning',
    plugins: [{
      // The examples are inlined rather than fetched: the site is served through a CDN
      // that refuses `.yaml` files with a 403, and a page that needs a request to show
      // its first example is a page that can fail to. The staleness test covers them.
      name: 'examples',
      setup(b) {
        b.onResolve({ filter: /^lpg-playground-examples$/ }, () => ({ path: 'examples', namespace: 'examples' }))
        b.onLoad({ filter: /.*/, namespace: 'examples' }, () => {
          const dir = join(ROOT, 'docs', 'examples')
          const all = Object.fromEntries(readdirSync(dir).filter((f) => f.endsWith('.lpg.yaml')).sort()
            .map((f) => [f.replace('.lpg.yaml', ''), readFileSync(join(dir, f), 'utf8')]))
          return { contents: `export default ${JSON.stringify(all)}`, loader: 'js' }
        })
      },
    }, {
      name: 'node-path-shim',
      setup(b) {
        b.onResolve({ filter: /^node:path$/ }, () => ({ path: 'path', namespace: 'shim' }))
        b.onLoad({ filter: /.*/, namespace: 'shim' }, () => ({ contents: PATH_SHIM, loader: 'js' }))
      },
    }],
  })
  return result.outputFiles[0].text
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = await buildPlayground()
  writeFileSync(BUNDLE, text)
  writeFileSync(PAGE, stampedPage(readFileSync(PAGE, 'utf8'), text))
  console.log(`${BUNDLE} (${Math.round(text.length / 1024)} KiB)`)
}
